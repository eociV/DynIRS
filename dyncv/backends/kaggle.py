"""Kaggle backend: one private script kernel per session on GPU T4 x2.

Kept apart from scripts/kaggle_auto.py on purpose (different code dataset, kernel names and state
file), so a teammate's dynirs-* sessions are never touched:
  code dataset   <code_owner>/dynirs-cv-code      (src, scripts, configs, dyncv)
  data           <user>/dyncv-prep (default)       kernel output: data prepared on Kaggle from Hugging Face
                 or <data_owner>/dynirs-dv         dataset uploaded from home (pass --data-owner)
  kernels        <user>/dyncv-<queue>-r<N>         session N+1 mounts session N's output to resume
  state          kaggle_ds/cv/state.json
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

from ..config import ROOT, STATE_DIR
from ..live import SECRETS_SLUG, local_repo

ACCELERATOR = "NvidiaTeslaT4"
CODE_SLUG, DATA_SLUG, OMEGA_SLUG = "dynirs-cv-code", "dynirs-dv", "dynirs-cv-omega"
PREP_SLUG = "dyncv-prep"
SESSION_FILE = "dyncv_session.json"

RUNNER = '''"""DynCV session {slug} (generated by dyncv/backends/kaggle.py)."""
import json, subprocess, sys
from pathlib import Path

QUEUE, ONLY, BUDGET_H = {queue!r}, {only!r}, {budget_h!r}
IN = Path("/kaggle/input")


def dirs():  # /kaggle/input and four levels below, shallowest first
    level = [IN]
    for _ in range(5):
        yield from level
        level = [c for d in level for c in sorted(d.iterdir()) if c.is_dir()]


def find(ok):
    return next((d for d in dirs() if ok(d)), None)


prev = find(lambda d: (d / "DynIRS" / "runs" / "remote").is_dir())
code = find(lambda d: (d / "dyncv" / "session.py").is_file() and not (d / "runs").exists()
            and not (prev and prev in d.parents))
data = find(lambda d: (d / "proc" / ".ready_train").is_file() or (d / "dv_proc.tar").is_file())
live = find(lambda d: (d / "live.json").is_file())
print("inputs:", dict(code=code, data=data, prev=prev, live=live), flush=True)
if code is None or data is None:
    raise SystemExit("{code_slug} or the data ({prep_slug} output / {data_slug}) is not attached")
args = [sys.executable, "-m", "dyncv.session", "run", "--queue", QUEUE, "--data-in", str(data),
        "--code-in", str(code), "--work", "/kaggle/working", "--budget-h", str(BUDGET_H)]
args += ["--prev-out", str(prev)] if prev else []
args += ["--live", str(live / "live.json")] if live else []
args += ["--only", *ONLY] if ONLY else []
rc = subprocess.run(args, cwd=str(code)).returncode
# exit 0 even on failure so Kaggle keeps /kaggle/working; the local side reads this file
Path("/kaggle/working/{session_file}").write_text(json.dumps({{"slug": {slug!r}, "rc": rc}}))
print("session rc", rc, flush=True)
'''

PREP_RUNNER = '''"""DynCV data preparation (generated by dyncv/backends/kaggle.py)."""
import subprocess, sys
from pathlib import Path

code = next((d for d in sorted(Path("/kaggle/input").rglob("session.py")) if d.parent.name == "dyncv"), None)
if code is None:
    raise SystemExit("dynirs-cv-code is not attached")
code = code.parent.parent
print("code:", code, flush=True)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "huggingface_hub", "scipy", "pillow"], check=True)
rc = subprocess.run([sys.executable, "-m", "dyncv.prep", "--work", "/tmp/dv", "--out", "/kaggle/working",
                     "--expect", {expect!r}, "--folds", {folds!r}], cwd=str(code)).returncode
sys.exit(rc)
'''


# ------------------------------------------------------------------------------ pure helpers

def kernel_slug(queue, rnd: int) -> str:
    stem = re.sub(r"[^a-z0-9]+", "-", Path(queue).stem.lower()).strip("-")
    return f"dyncv-{stem}-r{rnd}"


def queue_rel(queue) -> str:
    p = Path(queue).resolve()
    try:
        return p.relative_to(ROOT).as_posix()
    except ValueError:
        raise SystemExit(f"{queue}: the queue must live inside the repository (it ships in {CODE_SLUG})")


def kernel_metadata(user, code_owner, data_owner, slug, prev=None, live=False) -> dict:
    """data_owner None -> data from the user's prep kernel output, else <data_owner>/dynirs-dv.
    live -> also mount the private <user>/dyncv-secrets (HF token for live metrics)."""
    data = [f"{data_owner}/{DATA_SLUG}"] if data_owner else []
    data += [f"{user}/{SECRETS_SLUG}"] if live else []
    kernels = ([] if data_owner else [f"{user}/{PREP_SLUG}"]) + ([f"{user}/{prev}"] if prev else [])
    return {"id": f"{user}/{slug}", "title": slug, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_tpu": False,
            "enable_internet": True, "machine_shape": ACCELERATOR,
            "dataset_sources": [f"{code_owner}/{CODE_SLUG}"] + data,
            "competition_sources": [], "kernel_sources": kernels}


def prep_metadata(user, code_owner) -> dict:
    """CPU kernel (no GPU quota) with internet: downloads from Hugging Face and prepares the data."""
    return {"id": f"{user}/{PREP_SLUG}", "title": PREP_SLUG, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": False, "enable_tpu": False,
            "enable_internet": True, "dataset_sources": [f"{code_owner}/{CODE_SLUG}"],
            "competition_sources": [], "kernel_sources": []}


def render_prep(expect: dict, folds_rel: str) -> str:
    return PREP_RUNNER.format(expect=json.dumps(expect), folds=folds_rel)


def local_hashes(proc, cache=STATE_DIR / "label_hashes.json") -> dict:
    """{split: line-ending-normalised label hash} of the local prepared data, the reference for the
    prep kernel. Slow on Windows (~100k small files), so cached per .ready_<split> content."""
    from ..prep import label_hash

    cache = Path(cache)
    old = json.loads(cache.read_text()) if cache.exists() else {}
    out, new = {}, {}
    for f in sorted(Path(proc).glob(".ready_*")):
        s, key = f.name[len(".ready_"):], f.read_text().strip()
        hit = old.get(s)
        out[s] = hit["hash"] if hit and hit["ready"] == key else label_hash(proc, s)
        new[s] = {"ready": key, "hash": out[s]}
    if out:
        cache.parent.mkdir(parents=True, exist_ok=True)
        cache.write_text(json.dumps(new, indent=1))
    return out


def render_runner(slug, queue, only, budget_h) -> str:
    return RUNNER.format(slug=slug, queue=queue, only=list(only or []), budget_h=budget_h,
                         code_slug=CODE_SLUG, data_slug=DATA_SLUG, prep_slug=PREP_SLUG, session_file=SESSION_FILE)


def parse_status(text: str) -> str:
    t = text.lower()
    for key, word in (("cancel", "cancelled"), ("error", "error"), ("complete", "complete"),
                      ("running", "running"), ("queued", "queued")):
        if key in t:
            return word
    return "unknown"


def kaggle_user(arg=None) -> str:
    if arg:
        return arg
    if os.environ.get("KAGGLE_USERNAME"):
        return os.environ["KAGGLE_USERNAME"]
    f = Path(os.environ.get("KAGGLE_CONFIG_DIR", Path.home() / ".kaggle")) / "kaggle.json"
    if f.exists():
        return json.loads(f.read_text())["username"]
    rc, out = cli("config", "view", check=False)  # also works after `kaggle auth login` (OAuth)
    m = re.search(r"username:\s*(\S+)", out) if rc == 0 else None
    if m and m.group(1).lower() not in ("none", "null"):
        return m.group(1)
    raise SystemExit("no Kaggle user: run `uv run kaggle auth login` (or put kaggle.json in ~/.kaggle), "
                     "or pass --user")


def cli(*args, check=True):
    exe = Path(sys.executable).with_name("kaggle.exe" if os.name == "nt" else "kaggle")
    cmd = [str(exe) if exe.exists() else (shutil.which("kaggle") or "kaggle"), *args]
    r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    out = (r.stdout or "") + (r.stderr or "")
    if check and r.returncode:
        raise SystemExit(f"kaggle {' '.join(args)} failed:\n{out.strip()}")
    return r.returncode, out


# ------------------------------------------------------------------------------ backend

class KaggleBackend:
    name = "kaggle"

    def __init__(self, user=None, code_owner=None, data_owner=None, state_dir=STATE_DIR, run_cli=cli):
        self.user = kaggle_user(user)
        self.code_owner = code_owner or self.user
        self.data_owner = data_owner  # None: data from the user's dyncv-prep kernel output
        self.dir = Path(state_dir)
        self.cli = run_cli

    # -------------------------------------------------------------------------- state

    def _key(self, queue) -> str:
        return f"{self.user}/{Path(queue).stem}"

    def load_state(self) -> dict:
        f = self.dir / "state.json"
        return json.loads(f.read_text()) if f.exists() else {}

    def save_state(self, st):
        self.dir.mkdir(parents=True, exist_ok=True)
        (self.dir / "state.json").write_text(json.dumps(st, indent=1))

    def rounds(self, queue) -> list[dict]:
        return self.load_state().get(self._key(queue), [])

    def active(self, queue):
        r = self.rounds(queue)
        return r[-1]["slug"] if r and r[-1]["status"] in ("queued", "running", "unknown") else None

    def mark(self, sid, status=None, **info):
        st = self.load_state()
        for rounds in st.values():
            for r in rounds:
                if r["slug"] == sid:
                    r.update(info, **({"status": status} if status else {}))
        self.save_state(st)

    def failures(self, queue) -> int:
        """Failed sessions (not complete) at the end of the queue's history."""
        n = 0
        for r in reversed(self.rounds(queue)):
            if r["status"] == "complete":
                break
            if r["status"] in ("error", "cancelled"):
                n += 1
        return n

    def unfetched(self, queue):
        """Latest ended session whose output was never downloaded (e.g. the pull failed)."""
        r = [x for x in self.rounds(queue) if x["status"] in ("complete", "error", "cancelled")]
        return r[-1]["slug"] if r and not r[-1].get("fetched") and not r[-1].get("no_output") else None

    # -------------------------------------------------------------------------- Backend

    def submit(self, queue, only=None, budget_h=11.0, prev=None):
        st = self.load_state()
        rounds = st.setdefault(self._key(queue), [])
        # resume from the newest session that left usable output: a complete one, or a failed one
        # whose runs/remote could still be downloaded (last.pt of its last finished epoch)
        prev = prev or next((r["slug"] for r in reversed(rounds) if r["status"] == "complete" or r.get("fetched")), None)
        slug = kernel_slug(queue, len(rounds) + 1)
        d = self.dir / "kernels" / slug
        d.mkdir(parents=True, exist_ok=True)
        (d / "run.py").write_text(render_runner(slug, queue_rel(queue), only, budget_h))
        meta = kernel_metadata(self.user, self.code_owner, self.data_owner, slug, prev, live=local_repo() is not None)
        (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
        _, out = self.cli("kernels", "push", "-p", str(d))
        rounds.append({"slug": slug, "prev": prev, "pushed": time.strftime("%Y-%m-%d %H:%M:%S"), "status": "queued"})
        self.save_state(st)
        print(out.strip(), f"\npushed {self.user}/{slug} (resumes from: {prev or 'nothing'})", flush=True)
        return slug

    def status(self, sid):
        _, out = self.cli("kernels", "status", f"{self.user}/{sid}", check=False)
        return parse_status(out)

    def logs(self, sid):
        rc, out = self.cli("kernels", "logs", f"{self.user}/{sid}", check=False)
        return out if rc == 0 else ""

    def fetch(self, sid, dst):
        dl = self.dir / "out" / sid
        shutil.rmtree(dl, ignore_errors=True)
        dl.mkdir(parents=True)
        self.cli("kernels", "output", f"{self.user}/{sid}", "-p", str(dl), "--force",
                 "--file-pattern", rf"(runs/remote/|{re.escape(SESSION_FILE)})")
        found = sorted(dl.rglob("runs/remote"))
        if not found:
            raise SystemExit(f"{sid}: no runs/remote in the output (https://www.kaggle.com/code/{self.user}/{sid})")
        dst = Path(dst)
        dst.mkdir(parents=True, exist_ok=True)
        for d in sorted(p for p in found[0].iterdir() if p.is_dir()):
            shutil.copytree(d, dst / d.name, dirs_exist_ok=True)
        info = next(dl.rglob(SESSION_FILE), None)
        if info:
            print("session", info.read_text(), flush=True)
        shutil.rmtree(dl, ignore_errors=True)  # merged; keep only one copy of the checkpoints
        return dst

    # -------------------------------------------------------------------------- data from Hugging Face

    def prep(self, expect: dict, folds_rel: str, poll=120) -> dict:
        """Push the CPU prep kernel, wait for it, return its prep_check.json. Training sessions then
        mount its output (dv_proc.tar). Rerun only if the data or the fold file change."""
        d = self.dir / "kernels" / PREP_SLUG
        d.mkdir(parents=True, exist_ok=True)
        (d / "run.py").write_text(render_prep(expect, folds_rel))
        (d / "kernel-metadata.json").write_text(json.dumps(prep_metadata(self.user, self.code_owner), indent=1))
        print(self.cli("kernels", "push", "-p", str(d))[1].strip(), flush=True)
        while True:
            st = self.status(PREP_SLUG)
            print(time.strftime("%H:%M:%S"), PREP_SLUG, st, flush=True)
            if st in ("complete", "error", "cancelled"):
                break
            time.sleep(poll)
        dl = self.dir / "out" / PREP_SLUG
        shutil.rmtree(dl, ignore_errors=True)
        self.cli("kernels", "output", f"{self.user}/{PREP_SLUG}", "-p", str(dl), "--force",
                 "--file-pattern", r"prep_check\.json", check=False)
        f = next(dl.rglob("prep_check.json"), None)
        rep = json.loads(f.read_text()) if f else {"ok": False, "problems": ["no prep_check.json in the output"]}
        rep["status"] = st
        if st != "complete" or not rep.get("ok"):
            raise SystemExit(f"prep failed ({st}): {rep.get('problems')}\nlog: https://www.kaggle.com/code/{self.user}/{PREP_SLUG}")
        return rep

    # -------------------------------------------------------------------------- datasets

    def upload(self, what, proc=None, tag="cv5"):
        sys.path.insert(0, str(ROOT / "scripts"))
        import pack_kaggle

        out = self.dir / "datasets"
        if what == "code":
            slug = CODE_SLUG
            d = pack_kaggle.pack_code(ROOT, out, slug, self.user)
            shutil.copytree(ROOT / "dyncv", d / "dyncv", ignore=shutil.ignore_patterns("__pycache__"))
        elif what == "omega":  # cross-fitted weight files, for student sessions
            slug = OMEGA_SLUG
            d = pack_kaggle._fresh(out, slug)
            for w in sorted((Path(proc) / "ironly_w").glob(f"{tag}_*")):
                shutil.copytree(w, d / "ironly_w" / w.name)
            if not (d / "ironly_w").exists():
                raise SystemExit(f"no {proc}/ironly_w/{tag}_* (run python -m dyncv merge first)")
            (d / "stats").mkdir()
            for f in (Path(proc) / "stats").glob(f"omega_{tag}_*.json"):
                shutil.copy2(f, d / "stats" / f.name)
            pack_kaggle._meta(d, slug, self.user)
        else:
            raise ValueError(what)
        exists = self.cli("datasets", "status", f"{self.user}/{slug}", check=False)[0] == 0
        if exists:
            self.cli("datasets", "version", "-p", str(d), "-m", time.strftime("update %Y-%m-%d %H:%M"), "--dir-mode", "zip")
        else:
            self.cli("datasets", "create", "-p", str(d), "--dir-mode", "zip")
        print(f"{'new version of' if exists else 'created'} {self.user}/{slug}; waiting until ready ...", flush=True)
        for _ in range(120):
            if "ready" in self.cli("datasets", "status", f"{self.user}/{slug}", check=False)[1].lower():
                print("ready", flush=True)
                return
            time.sleep(30)
        print("still processing after 60 min; check the dataset page before pushing", flush=True)
