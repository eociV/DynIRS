"""Drive DynIRS queues on Kaggle from this machine: upload datasets, push a run, poll, pull results,
and push the next session until every job of the queue is done.

Needs the Kaggle CLI credentials (~/.kaggle/kaggle.json, or KAGGLE_USERNAME / KAGGLE_KEY), a
phone-verified account (GPU + internet), and the code / data datasets uploaded once:

  uv run scripts/kaggle_auto.py upload data                 # kaggle_ds/dynirs-dv  -> <user>/dynirs-dv
  uv run scripts/kaggle_auto.py upload code                 # again after every code change
  uv run scripts/kaggle_auto.py upload omega                # after src/omega.py weights (T / TL / S queues)

  uv run scripts/kaggle_auto.py run configs/queues/dyn/t4_v8n_s0_c.json     # push, poll, pull, repeat
  uv run scripts/kaggle_auto.py push configs/queues/dyn/t4_v8n_s0_c.json    # one session only
  uv run scripts/kaggle_auto.py status configs/queues/dyn/t4_v8n_s0_c.json
  uv run scripts/kaggle_auto.py pull   configs/queues/dyn/t4_v8n_s0_c.json  # latest session's runs

Each session is a separate private script kernel <user>/dynirs-<queue>-r<N> on GPU T4 x2. Session N+1
gets session N's output as a kernel source, so kaggle_session.py restores runs/ and training resumes
from last.pt. Pulled runs are merged into runs/remote/. State: kaggle_ds/auto/state.json.
Datasets owned by a teammate: pass --owner <their user> (they must share them with you).
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import pack_kaggle  # noqa: E402
import run_queue  # noqa: E402

KDS = ROOT / "kaggle_ds"
AUTO = KDS / "auto"
STATE = AUTO / "state.json"
DATASETS = {"data": "dynirs-dv", "code": "dynirs-code", "omega": "dynirs-omega"}
ACCELERATOR = "NvidiaTeslaT4"  # GPU T4 x2

RUNNER = '''"""DynIRS session {slug} (generated by scripts/kaggle_auto.py)."""
import json, subprocess, sys
from pathlib import Path

QUEUE, ONLY, BUDGET_H, MODS = {queue!r}, {only!r}, {budget_h!r}, {mods!r}
IN = Path("/kaggle/input")


def dirs():  # /kaggle/input and three levels below, shallowest first
    level = [IN]
    for _ in range(4):
        yield from level
        level = [c for d in level for c in sorted(d.iterdir()) if c.is_dir()]


def find(ok):
    return next((d for d in dirs() if ok(d)), None)


prev = find(lambda d: (d / "DynIRS" / "runs" / "remote").is_dir())
code = find(lambda d: (d / "scripts" / "kaggle_session.py").is_file() and not (d / "runs").exists()
            and not (prev and prev in d.parents))
data = find(lambda d: (d / "proc" / ".ready_train").is_file())
omega = find(lambda d: (d / "ironly_w").is_dir() and not (d / "proc").exists())
print("inputs:", dict(code=code, data=data, omega=omega, prev=prev), flush=True)
if code is None or data is None:
    raise SystemExit("dynirs-code or dynirs-dv is not attached")
args = [sys.executable, str(code / "scripts" / "kaggle_session.py"), "--queue", QUEUE, "--data-in", str(data),
        "--code-in", str(code), "--work", "/kaggle/working", "--budget-h", str(BUDGET_H), "--mods", *MODS]
args += ["--omega-in", str(omega)] if omega else []
args += ["--prev-out", str(prev)] if prev else []
args += ["--only", *ONLY] if ONLY else []
rc = subprocess.run(args).returncode
# exit 0 even on a failed lane, so Kaggle keeps /kaggle/working; kaggle_auto reads this file
Path("/kaggle/working/dynirs_session.json").write_text(json.dumps({{"slug": {slug!r}, "rc": rc}}))
print("session rc", rc, flush=True)
'''


# ------------------------------------------------------------------------------ pure helpers

def kernel_slug(queue, rnd):
    stem = re.sub(r"[^a-z0-9]+", "-", Path(queue).stem.lower()).strip("-")
    return f"dynirs-{stem}-r{rnd}"


def queue_rel(queue):
    """Queue path inside the code dataset (forward slashes, relative to the repository root)."""
    p = Path(queue).resolve()
    try:
        return p.relative_to(ROOT).as_posix()
    except ValueError:
        raise SystemExit(f"{queue}: the queue must live inside the repository (it ships in dynirs-code)")


def queue_needs(specs):
    """(needs ω files, modalities to pre-cache) for the jobs of a queue."""
    omega = any(s.get("config", {}).get("ir_soft_w_dir") for s in specs)
    data = {s.get("train", {}).get("data") for s in specs}
    mods = ["rgb"] + (["ir"] if data & {"ir", "mix"} else [])
    return omega, mods


def kernel_metadata(user, owner, slug, omega, prev=None):
    sources = [f"{owner}/{DATASETS['code']}", f"{owner}/{DATASETS['data']}"]
    sources += [f"{owner}/{DATASETS['omega']}"] if omega else []
    return {"id": f"{user}/{slug}", "title": slug, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_tpu": False,
            "enable_internet": True, "machine_shape": ACCELERATOR, "dataset_sources": sources,
            "competition_sources": [], "kernel_sources": [f"{user}/{prev}"] if prev else []}


def render_runner(slug, queue, only, budget_h, mods):
    return RUNNER.format(slug=slug, queue=queue, only=list(only or []), budget_h=budget_h, mods=list(mods))


def parse_status(text):
    """Kaggle CLI status line -> complete | error | cancelled | running | queued | unknown."""
    t = text.lower()
    for key, word in (("cancel", "cancelled"), ("error", "error"), ("complete", "complete"),
                      ("running", "running"), ("queued", "queued")):
        if key in t:
            return word
    return "unknown"


def pending(specs, runs, only=None):
    """Names of the queue's jobs that still have work left, judged from a runs/remote directory."""
    return [s["name"] for s in specs if (not only or s["name"] in only) and run_queue.plan(s, runs)]


# ------------------------------------------------------------------------------ Kaggle CLI

def kaggle(*args, check=True):
    exe = Path(sys.executable).with_name("kaggle.exe" if os.name == "nt" else "kaggle")
    cmd = [str(exe) if exe.exists() else (shutil.which("kaggle") or "kaggle"), *args]
    r = subprocess.run(cmd, capture_output=True, text=True)
    out = (r.stdout or "") + (r.stderr or "")
    if check and r.returncode:
        raise SystemExit(f"kaggle {' '.join(args)} failed:\n{out.strip()}")
    return r.returncode, out


def kaggle_user(arg=None):
    if arg:
        return arg
    if os.environ.get("KAGGLE_USERNAME"):
        return os.environ["KAGGLE_USERNAME"]
    for f in (Path(os.environ.get("KAGGLE_CONFIG_DIR", Path.home() / ".kaggle")) / "kaggle.json",):
        if f.exists():
            return json.loads(f.read_text())["username"]
    raise SystemExit("no Kaggle user: put kaggle.json in ~/.kaggle (Kaggle > Settings > API) or pass --user")


def load_state():
    return json.loads(STATE.read_text()) if STATE.exists() else {}


def save_state(st):
    AUTO.mkdir(parents=True, exist_ok=True)
    STATE.write_text(json.dumps(st, indent=1))


# ------------------------------------------------------------------------------ commands

def upload(what, user):
    proc = Path(os.environ.get("DV_DATA", ROOT / "data" / "dronevehicle")) / "proc"
    slug = DATASETS[what]
    d = {"data": lambda: pack_kaggle.pack_data(proc, KDS, slug, user),
         "omega": lambda: pack_kaggle.pack_omega(proc, KDS, slug, user),
         "code": lambda: pack_kaggle.pack_code(ROOT, KDS, slug, user)}[what]()
    exists = kaggle("datasets", "status", f"{user}/{slug}", check=False)[0] == 0
    if exists:
        kaggle("datasets", "version", "-p", str(d), "-m", time.strftime("update %Y-%m-%d %H:%M"), "--dir-mode", "zip")
    else:
        kaggle("datasets", "create", "-p", str(d), "--dir-mode", "zip")
    print(f"{'new version of' if exists else 'created'} {user}/{slug}; waiting until it is ready ...", flush=True)
    for _ in range(120):
        _, out = kaggle("datasets", "status", f"{user}/{slug}", check=False)
        if "ready" in out.lower():
            print("ready", flush=True)
            return
        time.sleep(30)
    print("still processing after 60 min; check the dataset page before pushing", flush=True)


def push(queue, user, owner, only=None, budget_h=11.0, prev=None):
    specs = json.loads(Path(queue).read_text())
    omega, mods = queue_needs([s for s in specs if not only or s["name"] in only])
    st = load_state()
    rounds = st.setdefault(Path(queue).stem, [])
    if prev is None and rounds:
        prev = rounds[-1]["slug"]
    slug = kernel_slug(queue, len(rounds) + 1)
    d = AUTO / "kernels" / slug
    d.mkdir(parents=True, exist_ok=True)
    (d / "run.py").write_text(render_runner(slug, queue_rel(queue), only, budget_h, mods))
    (d / "kernel-metadata.json").write_text(json.dumps(kernel_metadata(user, owner, slug, omega, prev), indent=1))
    _, out = kaggle("kernels", "push", "-p", str(d))
    rounds.append({"slug": slug, "prev": prev, "pushed": time.strftime("%Y-%m-%d %H:%M:%S"), "status": "queued"})
    save_state(st)
    print(out.strip(), flush=True)
    print(f"pushed {user}/{slug} (prev: {prev or 'none'}, omega: {omega}, cache: {mods})", flush=True)
    return slug


def status(slug, user):
    _, out = kaggle("kernels", "status", f"{user}/{slug}", check=False)
    return parse_status(out), out.strip()


def pull(slug, user):
    """Download the session's runs/ and merge them into runs/remote/. Returns the downloaded runs/remote."""
    dst = AUTO / "out" / slug
    shutil.rmtree(dst, ignore_errors=True)
    dst.mkdir(parents=True)
    kaggle("kernels", "output", f"{user}/{slug}", "-p", str(dst), "--force",
           "--file-pattern", r"(runs/remote/|dynirs_session\.json)")
    found = sorted(dst.rglob("runs/remote"))
    if not found:
        raise SystemExit(f"{slug}: no runs/remote in the output (see https://www.kaggle.com/code/{user}/{slug})")
    remote = found[0]
    run_queue.RUNS.mkdir(parents=True, exist_ok=True)
    for d in sorted(p for p in remote.iterdir() if p.is_dir()):
        shutil.copytree(d, run_queue.RUNS / d.name, dirs_exist_ok=True)
        print("merged", d.name, flush=True)
    info = next(dst.rglob("dynirs_session.json"), None)
    if info:
        print("session", info.read_text(), flush=True)
    return remote


def run(queue, user, owner, only=None, budget_h=11.0, poll=600, max_rounds=6):
    specs = json.loads(Path(queue).read_text())
    st = load_state()
    rounds = st.get(Path(queue).stem, [])
    slug = rounds[-1]["slug"] if rounds and rounds[-1]["status"] in ("queued", "running") else None
    for _ in range(max_rounds):
        slug = slug or push(queue, user, owner, only, budget_h)
        while True:
            s, line = status(slug, user)
            print(time.strftime("%H:%M:%S"), slug, s, flush=True)
            if s in ("complete", "error", "cancelled"):
                break
            time.sleep(poll)
        st = load_state()
        st[Path(queue).stem][-1]["status"] = s
        save_state(st)
        if s != "complete":
            raise SystemExit(f"{slug} ended with status {s}: {line}\nlog: https://www.kaggle.com/code/{user}/{slug}")
        left = pending(specs, pull(slug, user), only)
        if not left:
            print("queue done:", Path(queue).name, flush=True)
            return
        print("still to do:", ", ".join(left), "-> next session", flush=True)
        slug = None
    raise SystemExit(f"stopped after {max_rounds} sessions; rerun to continue")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--user", help="Kaggle user running the kernels (default: from kaggle.json)")
    ap.add_argument("--owner", help="owner of the dynirs-* datasets (default: --user)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    u = sub.add_parser("upload")
    u.add_argument("what", choices=sorted(DATASETS))
    for name in ("push", "run"):
        p = sub.add_parser(name)
        p.add_argument("queue")
        p.add_argument("--only", nargs="*")
        p.add_argument("--budget-h", type=float, default=11.0, help="lanes stop after this many hours (max session 12 h)")
        if name == "run":
            p.add_argument("--poll", type=int, default=600, help="seconds between status checks")
            p.add_argument("--max-rounds", type=int, default=6)
        else:
            p.add_argument("--prev", help="kernel slug whose output to resume from (default: last session)")
    for name in ("status", "pull"):
        p = sub.add_parser(name)
        p.add_argument("queue", help="queue file (uses its latest session) or a kernel slug")
    a = ap.parse_args(argv)
    user = kaggle_user(a.user)
    owner = a.owner or user
    if a.cmd == "upload":
        return upload(a.what, user)
    if a.cmd == "push":
        return push(a.queue, user, owner, a.only, a.budget_h, a.prev)
    if a.cmd == "run":
        return run(a.queue, user, owner, a.only, a.budget_h, a.poll, a.max_rounds)
    rounds = load_state().get(Path(a.queue).stem)
    slug = rounds[-1]["slug"] if rounds else a.queue
    if a.cmd == "status":
        s, line = status(slug, user)
        print(s, "|", line)
    else:
        pull(slug, user)


if __name__ == "__main__":
    main()
